# SECTION 2: CROP YIELD CONFUSION MATRIX (CODE & EVALUATION)
# ==============================================================================
def evaluate_crop_yield_confusion_matrix():
    print("=" * 80)
    print("2. EVALUATING CROP YIELD TIER CONFUSION MATRIX (12 Indian Crops, DES/ICRISAT)")
    print("=" * 80)

    yield_data_path = BASE_DIR / "data" / "crop_yield_data.csv"
    yield_model_path = BASE_DIR / "model" / "yield_model.joblib"

    if yield_data_path.exists() and yield_model_path.exists():
        df = pd.read_csv(yield_data_path)
        cat_cols = ["crop", "state", "season", "soil_type"]
        num_cols = ["area_hectares", "temperature", "humidity", "rainfall", "soil_ph", "soil_moisture", "irrigation"]
        target_col = "yield_per_hectare"

        X = df[cat_cols + num_cols].copy()
        if "irrigation" in X.columns:
            X["irrigation"] = X["irrigation"].astype(int)
        y = df[target_col].copy()

        X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=42)
        pipeline = joblib.load(yield_model_path)
        preds = pipeline.predict(X_test)

        mae = mean_absolute_error(y_test, preds)
        rmse = np.sqrt(mean_squared_error(y_test, preds))
        r2 = r2_score(y_test, preds)

        # Tercile thresholds fitted strictly on training data
        t33 = float(np.percentile(y_train, 33.333))
        t66 = float(np.percentile(y_train, 66.667))

        def categorize(yields, t1, t2):
            return np.array(["Low" if val <= t1 else ("Medium" if val <= t2 else "High") for val in yields])

        y_test_cat = categorize(y_test, t33, t66)
        preds_cat = categorize(preds, t33, t66)
        cat_labels = ["Low", "Medium", "High"]

        cm = confusion_matrix(y_test_cat, preds_cat, labels=cat_labels)
        cr = classification_report(y_test_cat, preds_cat, labels=cat_labels, digits=4)
        acc = accuracy_score(y_test_cat, preds_cat) * 100
        n_samples = len(y_test)
    else:
        with open(REPORTS_DIR / "yield_evaluation.json", "r", encoding="utf-8") as f:
            y_data = json.load(f)
        cm = np.array(y_data["categorization"]["confusion_matrix"])
        cat_labels = y_data["categorization"]["categories"]
        mae = y_data["regression_metrics"]["mae"]
        rmse = y_data["regression_metrics"]["rmse"]
        r2 = y_data["regression_metrics"]["r2"]
        acc = y_data["categorization"]["accuracy"]
        t33 = y_data["categorization"]["thresholds"]["low_max"]
        t66 = y_data["categorization"]["thresholds"]["medium_max"]
        n_samples = y_data["test_samples"]
        cr = json.dumps(y_data["categorization"]["classification_report"], indent=2)

    print(f"Test Samples Evaluated: {n_samples} records")
    print(f"Regression Performance: MAE = {mae:.4f} t/ha | RMSE = {rmse:.4f} t/ha | R² = {r2:.4f}")
    print(f"Agronomic Tiers: Low <= {t33:.2f} t/ha | Medium: {t33:.2f} to {t66:.2f} t/ha | High > {t66:.2f} t/ha")
    print(f"Overall Yield Tier Classification Accuracy: {acc:.2f}%\n")
    print("CONFUSION MATRIX (Rows: Actual, Columns: Predicted):")
    print(f"{'':>12} {'Pred Low':>12} {'Pred Medium':>12} {'Pred High':>12} {'Recall':>10}")
    print("-" * 62)
    row_recalls = [cm[i, i] / cm[i].sum() * 100 for i in range(3)]
    for idx, label in enumerate(cat_labels):
        print(f"Actual {label:<6}: {cm[idx, 0]:>12} {cm[idx, 1]:>12} {cm[idx, 2]:>12} {row_recalls[idx]:>9.2f}%")
    print("-" * 62)
    print("\nCLASSIFICATION REPORT:")
    print(cr)
    print("\n")


