export const ALL_KARNATAKA_DISTRICTS = Object.keys(KARNATAKA_LOCATION_DATA);

export const getTaluksForDistrict = (district) => {
  if (!district) return [];
  // Direct match
  if (KARNATAKA_LOCATION_DATA[district]) {
    return Object.keys(KARNATAKA_LOCATION_DATA[district].taluks || {});
  }
  // Case-insensitive / partial match
  const match = Object.keys(KARNATAKA_LOCATION_DATA).find(
    (d) => d.toLowerCase() === district.toLowerCase() ||
           district.toLowerCase().includes(d.toLowerCase()) ||
           d.toLowerCase().includes(district.toLowerCase())
  );
  if (match) {
    return Object.keys(KARNATAKA_LOCATION_DATA[match].taluks || {});
  }
  return [];
};

export const getVillagesForTaluk = (district, taluk) => {
  if (!district || !taluk) return [];
  const distKey = Object.keys(KARNATAKA_LOCATION_DATA).find(
    (d) => d.toLowerCase() === district.toLowerCase()
  ) || district;

  if (!KARNATAKA_LOCATION_DATA[distKey]) return [];
  const talukMap = KARNATAKA_LOCATION_DATA[distKey].taluks || {};
  
  if (talukMap[taluk]) return talukMap[taluk];
  
  // Case-insensitive taluk lookup
  const tMatch = Object.keys(talukMap).find(
    (t) => t.toLowerCase() === taluk.toLowerCase() ||
           t.toLowerCase().includes(taluk.toLowerCase()) ||
           taluk.toLowerCase().includes(t.toLowerCase())
  );
  return tMatch ? talukMap[tMatch] : [];
};

// Search across all 31 districts, taluks, and agricultural villages
export const searchLocations = (query) => {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();
  const results = [];

  for (const [dist, dData] of Object.entries(KARNATAKA_LOCATION_DATA)) {
    if (dist.toLowerCase().includes(q)) {
      results.push({ type: 'District', name: `${dist} District`, district: dist, taluk: '', village: '' });
    }
    for (const [tlk, vList] of Object.entries(dData.taluks || {})) {
      if (tlk.toLowerCase().includes(q)) {
        results.push({ type: 'Taluk', name: `${tlk} Taluk (${dist})`, district: dist, taluk: tlk, village: '' });
      }
      for (const vil of vList) {
        if (vil.toLowerCase().includes(q)) {
          results.push({ type: 'Village', name: `${vil}, ${tlk} (${dist})`, district: dist, taluk: tlk, village: vil });
        }
      }
    }
  }
  return results.slice(0, 20);
};
